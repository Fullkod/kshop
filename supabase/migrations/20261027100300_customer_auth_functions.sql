-- Phase 3: customer account helpers (D3, D5). The tables live in private (not exposed by PostgREST), so
-- the server reaches them through these functions; execute only for service_role.

-- Counts an attempt for a key and tells whether it is still within p_max in the last p_window_seconds.
-- Keys: login:{store}:{phone}, login-ip:{store}:{ip}, register-ip:{store}:{ip}, reset:{store}:{phone}…
create function public.auth_rate_limit(p_key text, p_window_seconds int, p_max int)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count int;
begin
  delete from private.auth_attempts
  where key = p_key and created_at < now() - make_interval(secs => p_window_seconds);
  insert into private.auth_attempts (key) values (p_key);
  select count(*) into v_count from private.auth_attempts where key = p_key;
  return v_count <= p_max;
end;
$$;

-- Clears the attempts of a key after a successful login.
create function public.auth_rate_limit_reset(p_key text)
returns void
language sql
security definer
set search_path = ''
as $$
  delete from private.auth_attempts where key = p_key;
$$;

-- Recovery code generated by the staff and sent over WhatsApp (no OpenWA yet, decision 23).
-- Only the HMAC of the code is stored; previous unused codes of the customer stop working.
create function public.customer_recovery_code_create(
  p_store_id uuid,
  p_customer_id uuid,
  p_code_hash text,
  p_ttl_minutes int,
  p_created_by uuid
)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_expires timestamptz := now() + make_interval(mins => p_ttl_minutes);
begin
  if not exists (select 1 from public.customers where id = p_customer_id and store_id = p_store_id) then
    raise exception 'Cliente no encontrado' using errcode = 'P0001', hint = 'not_found';
  end if;
  update private.customer_otps set consumed_at = now()
  where customer_id = p_customer_id and consumed_at is null;
  insert into private.customer_otps (store_id, customer_id, code_hash, expires_at, created_by)
  values (p_store_id, p_customer_id, p_code_hash, v_expires, p_created_by);
  return v_expires;
end;
$$;

-- Checks a recovery code. Never raises on a wrong code (the attempt counter must be kept):
-- status ok (returns the auth user), invalid, or locked after 5 wrong attempts.
create function public.customer_recovery_code_consume(p_store_id uuid, p_phone text, p_code_hash text)
returns table (status text, user_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_customer public.customers;
  v_otp private.customer_otps;
begin
  select * into v_customer from public.customers where store_id = p_store_id and phone = p_phone;
  if not found then
    return query select 'invalid'::text, null::uuid;
    return;
  end if;

  select * into v_otp from private.customer_otps
  where customer_id = v_customer.id and consumed_at is null and expires_at > now()
  order by created_at desc
  limit 1
  for update;
  if not found then
    return query select 'invalid'::text, null::uuid;
    return;
  end if;
  if v_otp.attempts >= 5 then
    return query select 'locked'::text, null::uuid;
    return;
  end if;
  if v_otp.code_hash <> p_code_hash then
    update private.customer_otps set attempts = attempts + 1 where id = v_otp.id;
    return query select (case when v_otp.attempts + 1 >= 5 then 'locked' else 'invalid' end)::text, null::uuid;
    return;
  end if;

  update private.customer_otps set consumed_at = now() where id = v_otp.id;
  return query select 'ok'::text, v_customer.user_id;
end;
$$;

revoke all on function public.auth_rate_limit(text, int, int), public.auth_rate_limit_reset(text),
  public.customer_recovery_code_create(uuid, uuid, text, int, uuid),
  public.customer_recovery_code_consume(uuid, text, text)
  from public, anon, authenticated;
grant execute on function public.auth_rate_limit(text, int, int), public.auth_rate_limit_reset(text),
  public.customer_recovery_code_create(uuid, uuid, text, int, uuid),
  public.customer_recovery_code_consume(uuid, text, text)
  to service_role;
